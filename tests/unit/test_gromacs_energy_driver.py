import hashlib
from pathlib import Path

import pytest

import cellulose_forge.energy_drivers.gromacs as gromacs_driver
from cellulose_forge.energy_drivers.gromacs import (
    normalize_gromacs_energies,
    parse_gromacs_xvg,
    run_gromacs_single_point,
)
from cellulose_forge.energy_drivers.report import validate_potential_sum


def _raw_terms() -> dict[str, float]:
    return {
        "Bond": 10.0,
        "Angle": 2.0,
        "U-B": 3.0,
        "Proper Dih.": 4.0,
        "Ryckaert-Bell.": 5.0,
        "Improper Dih.": 6.0,
        "LJ-14": 7.0,
        "LJ (SR)": 8.0,
        "Coulomb-14": 9.0,
        "Coulomb (SR)": 10.0,
        "Coul. recip.": 11.0,
        "Position Rest.": 12.0,
        "Disper. corr.": -1.0,
        "Potential": 86.0,
    }


def test_normalize_gromacs_energies_uses_canonical_complete_terms() -> None:
    report = normalize_gromacs_energies(_raw_terms(), coordinate_sha256="abc")

    assert report.engine == "gromacs"
    assert report.terms == {
        "bond": 10.0,
        "angle": 5.0,
        "dihedral": 9.0,
        "improper": 6.0,
        "vdw": 15.0,
        "electrostatics": 30.0,
        "restraint": 12.0,
        "dispersion_correction": -1.0,
        "potential": 86.0,
    }
    validate_potential_sum(report, absolute_kj_mol=0.0, relative=0.0)


def test_periodic_improper_is_not_folded_into_proper_dihedrals() -> None:
    raw = _raw_terms()
    raw["Per. Imp. Dih."] = 2.5
    raw["Potential"] += 2.5

    report = normalize_gromacs_energies(raw, coordinate_sha256="abc")

    assert report.terms["dihedral"] == 9.0
    assert report.terms["improper"] == 8.5


def test_cmap_fails_closed_when_nonzero() -> None:
    raw = _raw_terms()
    raw["CMAP"] = 3.0

    with pytest.raises(ValueError, match=r"unsupported nonzero.*CMAP"):
        normalize_gromacs_energies(raw, coordinate_sha256="abc")


def test_normalize_preserves_raw_terms_as_diagnostics() -> None:
    raw = _raw_terms()
    report = normalize_gromacs_energies(raw, coordinate_sha256="abc")
    raw["Bond"] = 999.0

    assert report.extra["raw_terms"]["Bond"] == 10.0


def test_normalize_rejects_unsupported_nonzero_term() -> None:
    raw = _raw_terms()
    raw["Pull"] = 1.0

    with pytest.raises(ValueError, match=r"unsupported nonzero.*Pull"):
        normalize_gromacs_energies(raw, coordinate_sha256="abc")


def test_normalize_allows_unknown_zero_diagnostic() -> None:
    raw = _raw_terms()
    raw["Kinetic En."] = 0.0

    report = normalize_gromacs_energies(raw, coordinate_sha256="abc")

    assert report.terms["potential"] == 86.0


@pytest.mark.parametrize("value", [float("nan"), float("inf"), True, "1.0"])
def test_normalize_rejects_invalid_values(value: object) -> None:
    raw: dict[str, object] = dict(_raw_terms())
    raw["Bond"] = value

    with pytest.raises((TypeError, ValueError), match="Bond"):
        normalize_gromacs_energies(raw, coordinate_sha256="abc")  # type: ignore[arg-type]


def test_normalize_requires_potential() -> None:
    raw = _raw_terms()
    del raw["Potential"]

    with pytest.raises(ValueError, match="missing Potential"):
        normalize_gromacs_energies(raw, coordinate_sha256="abc")


def test_parse_gromacs_xvg_text() -> None:
    text = """
# generated by gmx energy
@ s0 legend "Bond"
@ s1 legend "Potential"
 0.000000  1.25  1.25
"""

    assert parse_gromacs_xvg(text) == {"Bond": 1.25, "Potential": 1.25}


def test_parse_gromacs_xvg_path(tmp_path: Path) -> None:
    path = tmp_path / "energy.xvg"
    path.write_text('@ s0 legend "Potential"\n0 -3.5\n', encoding="utf-8")

    assert parse_gromacs_xvg(path) == {"Potential": -3.5}


@pytest.mark.parametrize(
    ("text", "message"),
    [
        ('@ s0 legend "Potential"\n0 -1\n1 -2\n', "one data row"),
        ('@ s1 legend "Potential"\n0 -1\n', "contiguous"),
        ('@ s0 legend "Potential"\n0 -1 2\n', "column count"),
        ('@ s0 legend "Potential"\n0 nan\n', "non-finite"),
    ],
)
def test_parse_gromacs_xvg_rejects_invalid_single_point_data(text: str, message: str) -> None:
    with pytest.raises(ValueError, match=message):
        parse_gromacs_xvg(text)


def test_run_gromacs_single_point_uses_explicit_matched_inputs(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    coordinates = tmp_path / "coordinates.g96"
    topology = tmp_path / "system.top"
    mdp = tmp_path / "single_point.mdp"
    coordinates.write_text("shared coordinates\n", encoding="utf-8")
    topology.write_text("topology\n", encoding="utf-8")
    mdp.write_text("nsteps = 0\nconstraints = none\n", encoding="utf-8")
    checksum = hashlib.sha256(coordinates.read_bytes()).hexdigest()
    commands: list[list[str]] = []

    def fake_run(command: list[str], *, directory: Path, stdin: str | None = None) -> str:
        assert directory == tmp_path.resolve()
        commands.append(command)
        if command[1] == "energy":
            assert stdin is not None and "CMAP" in stdin
            (tmp_path / "single_point_energy.xvg").write_text(
                '@ s0 legend "Bond"\n@ s1 legend "Potential"\n0 1.25 1.25\n',
                encoding="utf-8",
            )
        return ""

    monkeypatch.setattr(gromacs_driver, "_run", fake_run)
    report = run_gromacs_single_point(
        tmp_path,
        coordinate_file=coordinates,
        topology_file=topology,
        mdp_file=mdp,
        coordinate_sha256=checksum,
        executable="gmx-test",
    )

    assert [command[1] for command in commands] == ["grompp", "mdrun", "energy"]
    assert report.terms["bond"] == 1.25
    assert report.terms["potential"] == 1.25


def test_run_gromacs_single_point_rejects_checksum_or_constrained_mdp(tmp_path: Path) -> None:
    coordinates = tmp_path / "coordinates.g96"
    topology = tmp_path / "system.top"
    mdp = tmp_path / "single_point.mdp"
    coordinates.write_text("shared coordinates\n", encoding="utf-8")
    topology.write_text("topology\n", encoding="utf-8")
    mdp.write_text("nsteps = 0\nconstraints = h-bonds\n", encoding="utf-8")

    with pytest.raises(ValueError, match="shared checksum"):
        run_gromacs_single_point(
            tmp_path,
            coordinate_file=coordinates,
            topology_file=topology,
            mdp_file=mdp,
            coordinate_sha256="wrong",
        )

    checksum = hashlib.sha256(coordinates.read_bytes()).hexdigest()
    with pytest.raises(ValueError, match="constraints = none"):
        run_gromacs_single_point(
            tmp_path,
            coordinate_file=coordinates,
            topology_file=topology,
            mdp_file=mdp,
            coordinate_sha256=checksum,
        )
