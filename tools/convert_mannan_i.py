"""Generate the Mannan I crystal definition from Chanzy et al. (1987).

The primary paper reports Cartesian coordinates for one beta-D-mannose
residue and gives explicit transforms for the second residue of its chain and
for the antiparallel chain.  Coordinates are tabulated in units of 10^-4 nm;
the integer values below are transcribed verbatim from Table I.

The paper's O1 and the screw-related O4 are the same glycosidic oxygen.  The
CelluloseForge convention assigns that oxygen to O4 of the residue whose C4
it bonds, so O1 is deliberately omitted.  Hydroxyl hydrogens were not listed
in Table I.  HO2, HO3, and HO6 are placed at 0.96 A along the donor--acceptor
directions of the hydrogen-bond network described in the paper.  They are
therefore modelled coordinates, not experimentally refined sites.

Usage::

    python tools/convert_mannan_i.py
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

DATA = Path(__file__).resolve().parents[1] / "src/cellulose_forge/data/crystallography/mannan"
CELL = np.asarray([8.92, 7.21, 10.27])
OH_LENGTH = 0.96

# Rotations around each C--O axis, measured from the cone direction closest
# to the nominal acceptor.  Optimizing the three torsions together removes a
# 1.37 A HO3--HO6 contact generated by the individually most-linear choices.
# The rounded Table I heavy atoms make the O3...O5 contact unusually short,
# so the selected compromise maximizes periodic nonbonded clearance while
# retaining O--H...O angles close to or above 140 degrees.
HYDROXYL_TORSIONS_DEG = {"HO2": 17.4, "HO3": 25.85, "HO6": -28.75}

# Table I, Cartesian coordinates in 10^-4 nm. O1 is retained here only so the
# converter can prove that it duplicates the screw-related O4 site.
PUBLISHED = {
    "C1": (2250, 543, 3054),
    "C2": (3083, 1248, 1991),
    "C3": (2482, 1029, 611),
    "C4": (2284, -459, 351),
    "C5": (1503, -1093, 1497),
    "C6": (1371, -2595, 1354),
    "O1": (2906, 659, 4273),
    "O2": (4411, 739, 2020),
    "O3": (3349, 1580, -382),
    "O4": (1554, -659, -862),
    "O5": (2170, -850, 2745),
    "O6": (1317, -3244, 2623),
    "H1": (1330, 935, 3072),
    "H2": (3136, 2224, 2202),
    "H3": (1601, 1498, 552),
    "H4": (3175, -905, 268),
    "H5": (582, -704, 1530),
    "H61": (2158, -2952, 851),
    "H62": (531, -2810, 855),
}

ATOM_ORDER = (
    "C1", "H1", "C2", "H2", "C3", "H3", "C4", "H4", "C5", "H5",
    "C6", "H61", "H62", "O2", "O3", "O4", "O5", "O6", "HO2", "HO3", "HO6",
)


def _screw(coordinates: np.ndarray) -> np.ndarray:
    """Apply (x', y', z') = (-x+a/2, -y, z+c/2)."""
    result = coordinates * np.asarray([-1.0, -1.0, 1.0])
    return result + np.asarray([CELL[0] / 2.0, 0.0, CELL[2] / 2.0])


def _second_chain(coordinates: np.ndarray) -> np.ndarray:
    """Apply the proper two-fold operation (x+a/2, -y+b/2, -z)."""
    result = coordinates * np.asarray([1.0, -1.0, -1.0])
    return result + np.asarray([CELL[0] / 2.0, CELL[1] / 2.0, 0.0])


def _hydrogen(
    donor: np.ndarray,
    bonded_carbon: np.ndarray,
    acceptor: np.ndarray,
    rotation_deg: float,
) -> np.ndarray:
    """Place H on the tetrahedral C-O-H cone at a selected torsion."""
    carbon_direction = bonded_carbon - donor
    carbon_direction /= np.linalg.norm(carbon_direction)
    acceptor_direction = acceptor - donor
    acceptor_direction /= np.linalg.norm(acceptor_direction)
    perpendicular = (
        acceptor_direction
        - np.dot(acceptor_direction, carbon_direction) * carbon_direction
    )
    perpendicular /= np.linalg.norm(perpendicular)
    orthogonal = np.cross(carbon_direction, perpendicular)
    angle = np.radians(109.5)
    rotation = np.radians(rotation_deg)
    cone_direction = (
        np.cos(rotation) * perpendicular + np.sin(rotation) * orthogonal
    )
    oh_direction = np.cos(angle) * carbon_direction + np.sin(angle) * cone_direction
    return donor + OH_LENGTH * oh_direction


def definition() -> dict[str, object]:
    """Return the package definition derived from the published model."""
    xyz = {name: np.asarray(value, dtype=float) / 1000.0 for name, value in PUBLISHED.items()}

    # O1 of this residue is O4 of the next screw-related residue.
    duplicate_o4 = _screw(xyz["O4"])
    if not np.allclose(xyz["O1"], duplicate_o4, atol=5e-4):
        raise SystemExit("published O1 does not duplicate screw-related O4")

    next_xyz = {name: _screw(value) for name, value in xyz.items()}
    # Reported network: interchain O2-H...O5 and intrachain O3-H...O5 and
    # O6-H...O3. Select the corresponding proper-symmetry images, then place
    # H on a tetrahedral C-O-H cone rather than directly on the O...O line.
    interchain_o5 = _second_chain(_screw(xyz["O5"])) + np.asarray([0.0, 0.0, CELL[2]])
    xyz["HO2"] = _hydrogen(
        xyz["O2"], xyz["C2"], interchain_o5, HYDROXYL_TORSIONS_DEG["HO2"]
    )
    xyz["HO3"] = _hydrogen(
        xyz["O3"],
        xyz["C3"],
        next_xyz["O5"] - np.asarray([0.0, 0.0, CELL[2]]),
        HYDROXYL_TORSIONS_DEG["HO3"],
    )
    xyz["HO6"] = _hydrogen(
        xyz["O6"], xyz["C6"], next_xyz["O3"], HYDROXYL_TORSIONS_DEG["HO6"]
    )

    first = np.asarray([xyz[name] / CELL for name in ATOM_ORDER])
    second = _second_chain(np.asarray([xyz[name] for name in ATOM_ORDER])) / CELL
    return {
        "polymer": "mannan",
        "residue_name": "MAN",
        "allomorph": "I",
        "space_group": "P 21 21 21",
        "chain_axis": "c",
        "provenance": {
            "citation": (
                "Chanzy, H.; Perez, S.; Miller, D. P.; Paradossi, G.; Winter, W. T. "
                "Macromolecules 1987, 20, 2407-2413."
            ),
            "doi": "10.1021/ma00176a014",
            "transcribed_from": (
                "Table I Cartesian coordinates and the published chain transforms; "
                "converted by tools/convert_mannan_i.py"
            ),
            "notes": (
                "O1 duplicates the screw-related O4 and is stored once as O4. "
                "HO2, HO3, and HO6 were absent from Table I and are modelled at 0.96 A "
                "on tetrahedral C-O-H cones toward the published hydrogen-bond network; "
                "their torsions were optimized together to avoid periodic clashes."
            ),
        },
        "unit_cell": {
            "a": CELL[0], "b": CELL[1], "c": CELL[2],
            "alpha_deg": 90.0, "beta_deg": 90.0, "gamma_deg": 90.0,
            "length_unit": "angstrom",
        },
        "symmetry_operations": [
            {
                "name": "identity",
                "rotation": [[1, 0, 0], [0, 1, 0], [0, 0, 1]],
                "translation": [0.0, 0.0, 0.0],
            },
            {
                "name": "chain_screw",
                "description": "(-x+1/2, -y, z+1/2), generating residue 2 of each chain.",
                "rotation": [[-1, 0, 0], [0, -1, 0], [0, 0, 1]],
                "translation": [0.5, 0.0, 0.5],
            },
        ],
        "asymmetric_unit": {
            "description": "Two beta-D-mannose residues, one on each antiparallel chain.",
            "residue_atom_count": len(ATOM_ORDER),
            "chain_labels": ["origin", "center"],
            "chain_directions": [1, -1],
            "atom_labels": [*ATOM_ORDER, *ATOM_ORDER],
            "fractional_coordinates": np.vstack([first, second]).round(9).tolist(),
        },
    }


def main() -> None:
    DATA.mkdir(parents=True, exist_ok=True)
    path = DATA / "i.json"
    path.write_text(json.dumps(definition(), indent=1) + "\n", encoding="utf-8")
    print(path)


if __name__ == "__main__":
    main()
